import random
import string

class NoteFactory:
    """Фабрика для генерации тестовых данных (предопределенных или случайных)."""

    @staticmethod
    def create_valid_data(title: str = None, content: str = None) -> dict:
        """Генерирует корректные данные для заметки."""
        if title is None:
            title = "".join(random.choices(string.ascii_letters, k=8))
        if content is None:
            content = "This is a random note content generated by Factory."
        return {"title": title, "content": content}

    @staticmethod
    def create_invalid_data(scenario_type: str = "missing_title") -> dict:
        """Генерирует некорректные данные для проверки негативных сценариев."""
        if scenario_type == "missing_title":
            return {"content": "Content without title"}
        elif scenario_type == "missing_content":
            return {"title": "Title without content"}
        elif scenario_type == "wrong_types":
            return {"title": 12345, "content": True}
        return {}
